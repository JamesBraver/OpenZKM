package com.zelix.klassmaster.script.log;

import com.zelix.exceptions.LookupException;
import com.zelix.klassmaster.config.Options;
import com.zelix.klassmaster.constant.CopyrightConstants;
import com.zelix.utils.GlobalUtils;
import com.zelix.utils.collections.OrderedSet;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.Iterator;
import java.util.List;

public abstract class AbstractScriptLogger {
	protected boolean verbose;
	private int specialErrorCount;
	private int indentationLevel;
	private int messageCount;
	protected boolean throwOnFatalError;
	protected PrintWriter writer;
	private OrderedSet<String> uniqueLogMessages;
	private int errorCount;
	private OrderedSet<String> uniqueSpecialErrors;
	private int warningCount;

	protected AbstractScriptLogger(boolean verbose) {
		this.verbose = verbose;
	}

	public static String generateHeaderComment(String componentName) {
		return GlobalUtils.generateComment(new String[]{"Generated by " + CopyrightConstants.NAME + " " + CopyrightConstants.VERSION + " " + componentName + " " + GlobalUtils.getCurrentTime()});
	}

	public String getIndentationSuffix() {
		if (this.getIndentationLevel() > 0) {
			this.decrementIndent();
			return Options.useDotIndentSuffix ? " ." : " ";
		} else {
			return "";
		}
	}

	public PrintWriter getWriter() {
		return this.writer;
	}

	public void incrementIndent() {
		this.indentationLevel++;
	}

	public int decrementIndent() {
		return this.indentationLevel--;
	}

	public int getErrorCount() {
		return this.errorCount;
	}

	public final void logMessageInternal(String message, boolean indented) {
		String logLine = (indented ? "\t" : "") + "MESSAGE: " + message + this.getIndentationSuffix();
		if (this.uniqueLogMessages == null) {
			this.uniqueLogMessages = new OrderedSet<>();
		}

		if (this.uniqueLogMessages.add(logLine)) {
			this.messageCount++;
			this.writer.println(logLine);
		}
	}

	public final void logWarningInternal(String message, boolean indented) {
		String logLine = (indented ? "\t" : "") + "WARNING: " + message + this.getIndentationSuffix();
		if (this.uniqueLogMessages == null) {
			this.uniqueLogMessages = new OrderedSet<>();
		}

		if (this.uniqueLogMessages.add(logLine)) {
			this.warningCount++;
			this.writer.println(logLine);
		}
	}

	public final void logErrorInternal(String message, boolean indented) {
		String logLine = (indented ? "\t" : "") + "ERROR: " + message + this.getIndentationSuffix();
		if (this.uniqueLogMessages == null) {
			this.uniqueLogMessages = new OrderedSet<>();
		}

		if (this.uniqueLogMessages.add(logLine)) {
			this.writer.println(logLine);
			this.errorCount++;
		}
	}

	public int getWarningCount() {
		return this.warningCount;
	}

	public boolean isVerbose() {
		if (true) return true;
		return this.verbose;
	}

	public void clearMessageCache() {
		this.uniqueLogMessages = null;
		this.uniqueSpecialErrors = null;
	}

	public List<String> getMessagesAsList() {
		ArrayList<String> messages = new ArrayList<>(this.uniqueLogMessages == null ? 0 : this.uniqueLogMessages.size());
		if (this.uniqueLogMessages != null) {
			for (String message : this.uniqueLogMessages) {
				messages.add(message);
			}
		}

		return messages;
	}

	public String getMessagesAsString() {
		if (this.uniqueLogMessages == null) {
			return null;
		} else {
			StringBuilder messageBuffer = new StringBuilder();
			int messageIndex = 0;

			for (Iterator<String> messageIterator = this.uniqueLogMessages.iterator(); messageIterator.hasNext(); messageIndex++) {
				if (messageIndex > 0) {
					messageBuffer.append(Options.lineSeparator);
				}

				messageBuffer.append(messageIterator.next());
			}

			return messageBuffer.toString();
		}
	}

	public void logMessage(String message) {
		this.logMessageInternal(message, false);
	}

	public final void logWarning(String message) {
		this.logWarningInternal(message, false);
	}

	public final void logSpecialError(String message) {
		this.logSpecialErrorInternal(message, false);
	}

	public int getMessageCount() {
		return this.messageCount;
	}

	public String getSpecialErrorsAsString() {
		if (this.uniqueSpecialErrors == null) {
			return null;
		} else {
			StringBuilder errorBuffer = new StringBuilder();
			int errorIndex = 0;

			for (Iterator<String> errorIterator = this.uniqueSpecialErrors.iterator(); errorIterator.hasNext(); errorIndex++) {
				if (errorIndex > 0) {
					errorBuffer.append(Options.lineSeparator);
				}

				errorBuffer.append(errorIterator.next());
			}

			return errorBuffer.toString();
		}
	}

	public final void logSpecialErrorInternal(String message, boolean indented) {
		String logLine = (indented ? "\t" : "") + "ERROR: " + message + this.getIndentationSuffix();
		if (this.uniqueLogMessages == null) {
			this.uniqueLogMessages = new OrderedSet<>();
		}

		if (this.uniqueSpecialErrors == null) {
			this.uniqueSpecialErrors = new OrderedSet<>();
		}

		if (this.uniqueLogMessages.add(logLine)) {
			this.writer.println(logLine);
			this.uniqueSpecialErrors.add(logLine);
			this.specialErrorCount++;
		}
	}

	public final void logError(String message) {
		this.logErrorInternal(message, false);
	}

	public final void logFatalError(String message) {
		String logLine = "FATAL ERROR: " + message + this.getIndentationSuffix();
		System.err.println(logLine);
		this.writer.println(logLine);
		this.writer.close();
		if (this.throwOnFatalError) {
			throw new LookupException(logLine);
		} else {
			System.exit(1);
		}
	}

	public int getIndentationLevel() {
		return this.indentationLevel;
	}

	public void close() {
		this.writer.close();
	}

	public final void logRaw(String line, boolean indented) {
		String logLine = (indented ? "\t" : "") + line;
		this.writer.println(logLine);
	}

	public int getSpecialErrorCount() {
		return this.specialErrorCount;
	}
}
