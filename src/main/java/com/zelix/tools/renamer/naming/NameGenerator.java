	public NameGenerator(char[] firstChars, char[] followingChars, List<String> reservedNames, boolean randomizeObfuscation) {
		this.reservedNames = reservedNames != null ? new ArrayList<>(reservedNames) : null;
		if (randomizeObfuscation && !Options.dontShuffleNameAlphabet) {
			Random random = GlobalUtils.newRandom(322);
			if (this.reservedNames != null) {
				GlobalUtils.shuffle(this.reservedNames, random);
			}

			char[] shuffledFirstChars = new char[firstChars.length];
			System.arraycopy(firstChars, 0, shuffledFirstChars, 0, firstChars.length);
			GlobalUtils.shuffle(shuffledFirstChars, random);
			firstChars = shuffledFirstChars;
			char[] shuffledFollowingChars = new char[followingChars.length];
			System.arraycopy(followingChars, 0, shuffledFollowingChars, 0, followingChars.length);
			GlobalUtils.shuffle(shuffledFollowingChars, random);
			followingChars = shuffledFollowingChars;
		}

		this.firstSequence = new NameSequence(firstChars, String.valueOf(this.sequenceId++));
		this.followingChars = followingChars;
		this.currentSequence = this.firstSequence;
	}

	private static boolean isKeyword(String name) {
		return JavaKeywords.keywords.contains(name);
	}

	public final String nextName() {
		if (this.reservedNames != null && this.reservedNames.size() > 0) {
			return this.reservedNames.remove(0);
		} else {
			String candidateName;
			do {
				candidateName = this.next();
			} while (isKeyword(candidateName));

			return candidateName;
		}
	}

	private String next() {
		this.nameBuilder.setLength(0);
		this.firstSequence.appendName(this.nameBuilder);
		if (this.currentSequence.advance()) {
			NameSequence exhaustedSequence = this.currentSequence;
			this.currentSequence = new NameSequence(this.followingChars);
			this.currentSequence.setParent(exhaustedSequence);
		}

		return this.nameBuilder.toString();
	}

	public final String next(String prefix) {
		if (prefix == null) {
			return this.nextName();
		} else if (this.reservedNames != null && this.reservedNames.size() > 0) {
			return prefix + this.reservedNames.remove(0);
		} else {
			String candidateName;
			do {
				this.prefixedNameBuilder.setLength(0);
				this.prefixedNameBuilder.append(prefix);
				candidateName = this.prefixedNameBuilder.append(this.next()).toString();
			} while (isKeyword(candidateName));

			return candidateName;
		}
	}
